def main() -> None:
    legacy: list[dict] = []
    with open(INPUT_PATH, "r", encoding="utf-8") as input_file:
        for line in input_file:
            line = line.strip()
            if line:
                legacy.append(json.loads(line))

    if len(legacy) > 40:
        legacy = legacy[:40]

    merged: list[dict] = []
    for item in legacy:
        if "query_type" not in item:
            item["query_type"] = default_query_type(item)
        merged.append(item)

    existing_ids = {item["id"] for item in merged}
    for item in NEW_QUESTIONS:
        if item["id"] in existing_ids:
            raise ValueError(f"重复题目 id：{item['id']}")
        merged.append(item)

    if len(merged) != 90:
        raise ValueError(f"期望 90 题，实际 {len(merged)}")

    with open(OUTPUT_PATH, "w", encoding="utf-8") as output_file:
        for item in merged:
            output_file.write(json.dumps(item, ensure_ascii=False) + "\n")

    counts: dict[str, int] = {}
    for item in merged:
        query_type = item.get("query_type", "factual")
        counts[query_type] = counts.get(query_type, 0) + 1

    print(f"已写入 {OUTPUT_PATH}，共 {len(merged)} 题")
    print("query_type 分布：", counts)


if __name__ == "__main__":
    main()
